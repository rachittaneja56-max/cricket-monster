import {chromium} from '@playwright/test';
import {mkdirSync,renameSync,writeFileSync} from 'node:fs';
import path from 'node:path';
const out=path.resolve(process.env.ARTIFACT_DIR||'out/verification');
mkdirSync(out,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:900},reducedMotion:'no-preference',recordVideo:{dir:out,size:{width:1440,height:900}}});
const page=await context.newPage();
await page.goto(process.env.BASE_URL||'http://127.0.0.1:8080/',{waitUntil:'networkidle'});
await page.waitForFunction(()=>{const v=document.querySelector('video');return v.readyState===4&&!v.paused;});
await page.waitForFunction(()=>{const v=document.querySelector('video');return v.currentTime>4.35&&v.currentTime<4.65;});
const before=await page.locator('video').evaluate(v=>({time:v.currentTime,paused:v.paused,frames:v.getVideoPlaybackQuality().totalVideoFrames}));
await page.screenshot({path:path.join(out,'hero-playing-desktop.jpg')});
await page.waitForTimeout(650);
const after=await page.locator('video').evaluate(v=>({time:v.currentTime,paused:v.paused,frames:v.getVideoPlaybackQuality().totalVideoFrames}));
await page.waitForTimeout(5000);
const recorded=page.video();
await context.close();
renameSync(await recorded.path(),path.join(out,'hero-playing-browser.webm'));
writeFileSync(path.join(out,'playback-capture.json'),JSON.stringify({before,after},null,2));
await browser.close();
console.log(JSON.stringify({before,after}));
